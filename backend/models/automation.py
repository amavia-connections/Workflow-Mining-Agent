"""
Data models for Automation Specifications generated by the Agent and human review gates.
"""
from datetime import datetime
from typing import Optional, List, Dict, Any
from enum import Enum
from pydantic import BaseModel, Field


class ApprovalStatus(str, Enum):
    PENDING_REVIEW = "PENDING_REVIEW"
    APPROVED = "APPROVED"
    REJECTED = "REJECTED"
    REVISION_REQUESTED = "REVISION_REQUESTED"


class AutomationStep(BaseModel):
    step_number: int
    step_name: str
    target_system_or_api: str
    action_description: str
    decision_rule: Optional[str] = None
    is_grounded_in_evidence: bool = True
    evidence_source_note: Optional[str] = None
    is_recommendation_only: bool = False


class HumanApprovalGate(BaseModel):
    required: bool = True
    approval_role: str = "Engineering Manager / Security Lead"
    justification: str = "Privilege escalation or state-changing production mutation requires human verification"


class AutomationSpecification(BaseModel):
    draft_id: str = Field(..., description="Unique specification identifier (e.g. SPEC-WF-ACCESS-01)")
    workflow_id: str = Field(..., description="Associated workflow ID")
    workflow_name: str
    business_objective: str
    problem_statement: str
    trigger_conditions: List[str]
    required_input_fields: List[str]
    systems_and_apis_involved: List[str]
    preconditions: List[str]
    ordered_steps: List[AutomationStep]
    decision_rules: List[str]
    exception_handling: List[str]
    human_approval_gate: HumanApprovalGate
    security_and_permission_requirements: List[str]
    retry_strategy_and_idempotency: str
    logging_and_audit_requirements: List[str]
    rollback_and_recovery_strategy: str
    testing_strategy_and_acceptance_criteria: List[str]
    estimated_implementation_complexity: str
    estimated_annual_hours_saved: float
    dependencies_and_unresolved_assumptions: List[str]
    pseudocode_or_workflow_definition: str
    
    # Evidence linkage
    evidence_ticket_ids: List[str] = []
    
    # Review & approval state
    approval_status: ApprovalStatus = ApprovalStatus.PENDING_REVIEW
    reviewer_name: Optional[str] = None
    reviewer_comments: Optional[str] = None
    reviewed_at: Optional[datetime] = None
    
    # Mandatory Safety Boundary Notice
    safety_boundary_notice: str = (
        "MANDATORY SAFETY BOUNDARY: Approval is a recorded review decision, NOT permission "
        "to execute the proposed automation. This system NEVER executes generated automations automatically."
    )
    created_at: datetime = Field(default_factory=datetime.utcnow)


class ReviewRequest(BaseModel):
    action: ApprovalStatus  # APPROVED, REJECTED, REVISION_REQUESTED
    reviewer_name: str = "Demo User (Security & DevOps Reviewer)"
    reviewer_role: Optional[str] = "Governance Approver"
    comments: Optional[str] = None
